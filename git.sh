#!/bin/bash

# Default values
commit_message="Automated commit"
branch="main"
new_branch=false
add_all=false

# Define help menu
help_menu() {
  echo "Usage: ./git-script.sh [OPTIONS]"
  echo ""
  echo "OPTIONS:"
  echo "  -a, --all              add all changes"
  echo "  -b, --branch <name>    specify branch (default: main)"
  echo "  -n, --new <name>       create new branch and switch to it"
  echo "  -m, --message <msg>    custom commit message (default: Automated commit)"
  echo "  -h, --help             display this help menu"
  echo ""
  echo "This script was generated by ChatGPT, a language model trained by OpenAI."
  echo ""
  exit 1
}

# Parse arguments
while [[ $# -gt 0 ]]
do
key="$1"

case $key in
    -a|--all)
    add_all=true
    shift
    ;;
    -b|--branch)
    branch="$2"
    shift
    shift
    ;;
    -n|--new)
    branch="$2"
    new_branch=true
    shift
    shift
    ;;
    -m|--message)
    commit_message="$2"
    shift
    shift
    ;;
    -h|--help)
    help_menu
    ;;
    *)
    break
    ;;
esac
done

# Check if any files are specified
if [[ $# -eq 0 && "$add_all" = false ]]
then
  help_menu
fi

# Create new branch if option is provided
if [ "$new_branch" = true ]
then
  git checkout -b $branch
fi

# Add changes
if [ "$add_all" = true ]
then
  git add --all
else
  git add "$@"
fi

# Commit changes
username=$(git config user.name)
commit_message="$commit_message ($(date +%Y-%m-%d)) [branch: $branch, author: $username]"
git commit -m "$commit_message"

# Push changes
git push origin $branch

# Revert back to default branch
if [ "$new_branch" = true ]
then
  git checkout main
fi
