#!/bin/bash

# Default values
commit_message="Automated commit"
branch="dev"
new_branch=false
add_all=false
show_diff=false

# Define help menu
help_menu() {
  echo "Usage: ./git-script.sh [OPTIONS] [FILES]"
  echo ""
  echo "OPTIONS:"
  echo "  -a, --all              add all changes"
  echo "  -b, --branch <name>    specify branch (default: dev)"
  echo "  -n, --new <name>       create new branch and switch to it"
  echo "  -c, --commit <msg>     custom commit message (default: Automated commit)"
  echo "  -d, --diff             show git diff --stat before committing or when it's the only argument"
  echo "  -h, --help             display this help menu"
  echo ""
  echo "This script was generated by ChatGPT, a language model trained by OpenAI."
  echo ""
  exit 1
}

# Parse arguments
while [[ $# -gt 0 ]]
do
  key="$1"

  case $key in
    -a|--all)
      add_all=true
      shift
      ;;
    -b|--branch)
      branch="$2"
      shift
      shift
      ;;
    -n|--new)
      branch="$2"
      new_branch=true
      shift
      shift
      ;;
    -c|--commit)
      commit_message="$2"
      shift
      shift
      ;;
    -d|--diff)
      show_diff=true
      shift
      ;;
    -h|--help)
      help_menu
      ;;
    *)
      break
      ;;
  esac
done

# Check if any files are specified
if [[ $# -eq 0 && "$add_all" = false && "$show_diff" = false ]]
then
  help_menu
fi

# Create new branch if option is provided
if [ "$new_branch" = true ]
then
  git checkout -b $branch
fi

# Show git diff --stat and skip all other steps
if [ "$show_diff" = true ] && [ "$#" -eq 0 ]
then
  git diff --stat
  exit 0
fi
# Add changes
if [ "$add_all" = true ]

then
  git add --all
else
  if [[ $# -gt 0 ]]
  then
    git add "$@"
  fi
fi

# Check if commit message is empty
# if [[ "$commit_message" == "" ]] && [ "$show_diff" = false ]
# then
#   echo "No commit message provided. Please specify a commit message using the -c or --commit option."
#   exit 1
# fi

# Commit changes if both add and commit options are true
if [ "$add_all" = true ] && [ "$commit_message" != "Automated commit" ]
then
  # Commit changes
  username=$(git config user.name)
  commit_message="$commit_message ($(date +%Y-%m-%d)) [branch: $branch, author: $username]"
  git commit -m "$commit_message"

  # Push changes if specified
  if [ "$push_changes" = true ]
  then
    git push origin "$branch"
  fi

  # Revert back to default branch
  if [ "$new_branch" = true ]
  then
    git checkout dev
  fi
fi